export function createTranslator(language) {
  const dictionary = translations[language] ?? translations.tr;

  return function translate(key, values = {}) {
    return Object.entries(values).reduce(
      (text, [name, value]) => text.replaceAll('{' + name + '}', String(value)),
      dictionary[key] ?? translations.tr[key] ?? key,
    );
  };
}

export function translateSectionLabel(label, language) {
  return language === 'en' ? sectionLabels[label] ?? label : label;
}

export function translateColorName(name, language) {
  return language === 'en' ? colorNames[name] ?? name : name;
}
